"""Readable Markdown report of a run."""

from __future__ import annotations

from typing import Any


def _fmt(v: float | None, digits: int = 4) -> str:
    return "–" if v is None else f"{v:.{digits}g}"


def markdown(cert: dict[str, Any]) -> str:
    b, d, m = cert["bounds"], cert["design"], cert["material"]
    setup = cert["setup"]
    lines = [
        "# Design report",
        "",
        f"Generated by {cert['tool']['name']} {cert['tool']['version']} on "
        f"{cert['created_utc']}.",
        "",
        "![Design](design.png)",
        "",
        "Dark: material. Blue: preserved regions. Pink: keep-out regions. Grey squares: "
        "supported nodes. Orange: loads.",
        "",
        "## Result",
        "",
        "| | |",
        "| --- | --- |",
        f"| Status | {b['status']} |",
        f"| Material | {m['name']} |",
        f"| Envelope | {setup['envelope']['width_mm']} × {setup['envelope']['height_mm']} × "
        f"{setup['envelope']['thickness_mm']} mm, {cert['model']['nx']} × {cert['model']['ny']}"
        f" elements |",
        f"| Material used | {d['solid_elements']} of {d['max_solid_elements']} allowed elements "
        f"({100 * d['volume_fraction']:.1f} % of the envelope) |",
        f"| Mass | {d['mass_kg']:.4g} kg |",
    ]
    if b["status"] == "certified":
        t = b["target"]
        lines += [
            f"| Compliance (upper bound) | {b['upper_bound_Nmm']:.6g} N·mm |",
            f"| Proven lower bound | {b['lower_bound_adjusted_Nmm']:.6g} N·mm |",
            f"| Optimality gap | {b['gap_percent']:.2f} % |",
            f"| Target (≤ {100 * t['gap_max']:.0f} %) | {'met' if t['met'] else 'not met'} |",
            f"| Stretch target (≤ {100 * t['stretch_gap_max']:.0f} %) | "
            f"{'met' if t['stretch_met'] else 'not met'} |",
            "",
            f"**What is proven:** {b['statement']}",
        ]
    elif b["status"] == "infeasible":
        lines += ["", "**The design is infeasible:**", ""] + [f"- {i}" for i in b["issues"]]
    else:
        lines += [f"| Compliance | {_fmt(b.get('upper_bound_Nmm'))} N·mm |", "",
                  f"**No bound established:** {b.get('reason', '')}"]
    lines += ["", "## Model and numerics", ""]
    lines += [f"- {a}" for a in cert["model"]["assumptions"]]
    num = cert["numerics"]
    lines += [f"- {num['precision']}; {num['linear_solver']}"]
    if "relative_margin" in num:
        lines += [f"- Largest relative solver residual: "
                  f"{max(num['upper_bound_relative_residual'], num['lower_bound_relative_residual']):.2e};"
                  f" both bounds widened by a relative margin of {num['relative_margin']:.1e}"]
    if cert.get("optimizer"):
        o = cert["optimizer"]
        lines += [f"- Optimizer: {o['method']}; {o['iterations']} iterations"
                  f"{', interrupted' if o['interrupted'] else ''}"
                  f"{', converged' if o['converged'] else ''}; KKT residual "
                  f"{o['kkt_residual']:.2e}"]
    sc = cert.get("stress_check")
    if sc:
        lines += ["", "## Stress check", "", f"*{sc['note']}*", ""]
        a = sc["allowables"]
        if a:
            source_note = (" MIL-HDBK-5J is superseded by MMPDS; these margins are not valid "
                           "for certification." if "MIL-HDBK-5J" in a["description"] else "")
            lines += [f"Allowables: yield {a['yield_MPa']:.1f} MPa, ultimate "
                      f"{a['ultimate_MPa']:.1f} MPa ({a['description']}).{source_note}", "",
                      "Yield is checked at limit load and ultimate at ultimate load "
                      "(limit × factor of safety).", ""]
        lines += [f"Factor of safety {sc['factor_of_safety']}, fitting factor "
                  f"{sc['fitting_factor']} in preserved regions.", "",
                  "| Load case | Max von Mises at limit load | Location | MS yield | MS ultimate |",
                  "| --- | --- | --- | --- | --- |"]
        for c in sc["load_cases"]:
            loc = f"({c['location_mm'][0]:.1f}, {c['location_mm'][1]:.1f}) mm"
            lines.append(f"| {c['name']} | {c['max_von_mises_at_limit_load_MPa']:.1f} MPa | {loc}"
                         f" | {_fmt(c.get('ms_yield'), 3)} | {_fmt(c.get('ms_ultimate'), 3)} |")
        verdict = {True: "passed", False: "FAILED", None: "no margins (no strength data)"}
        lines += ["", f"Stress check: **{verdict[sc['passed']]}**."]
        if sc["warnings"]:
            lines += [""] + [f"- {w}" for w in sc["warnings"]]
    lines += ["", "## Material sources", ""]
    for key, src in m["sources"].items():
        lines.append(f"- {key}: {src.get('citation', '')}")
    return "\n".join(lines) + "\n"
